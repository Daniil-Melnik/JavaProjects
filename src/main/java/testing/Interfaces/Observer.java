package testing.Interfaces;

/**
 * Интерфейс наблюдателя из паттерна "Наблюдатель" (Observer).
 * Наблюдатели получают уведомления об изменениях в модели.
 */
public interface Observer {

    /**
     * Вызывается при изменении наблюдаемого объекта.
     * Позволяет обновить состояние наблюдателя.
     */
    void update();
}